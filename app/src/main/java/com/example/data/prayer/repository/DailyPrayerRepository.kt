    fun getAllPrayers(): List<DailyPrayerVerse> = prayerList

    fun getPrayerById(id: Int): DailyPrayerVerse {
        return prayerList.find { it.id == id } ?: getTodayPrayer()
    }

    fun getPrayerForDay(dayNumber: Int): DailyPrayerVerse {
        val normalized = ((dayNumber - 1) % prayerList.size + prayerList.size) % prayerList.size
        return prayerList[normalized]
    }

    fun getTodayPrayer(): DailyPrayerVerse {
        val calendar = Calendar.getInstance()
        val dayOfYear = calendar.get(Calendar.DAY_OF_YEAR)
        val dayIndex = (dayOfYear - 1) % prayerList.size
        return prayerList[dayIndex]
    }
